const assert = require('node:assert/strict')
const { chromium } = require(process.env.PEERGRADE_PLAYWRIGHT || 'playwright')

async function main() {
  const origin = new URL(process.env.PEERGRADE_LOCAL_ORIGIN)
  assert.equal(origin.hostname, '127.0.0.1', 'Use a fresh local instance with synthetic preview accounts only.')
  assert.equal(origin.protocol, 'http:')
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PEERGRADE_BROWSER })
  async function login(username, viewport) {
    const context = await browser.newContext({ viewport })
    const page = await context.newPage()
    await page.goto(origin.href)
    await page.getByLabel('用户名').fill(username)
    await page.getByLabel('密码').fill('preview123456')
    await page.getByRole('button', { name: '登录 →' }).click()
    await page.getByLabel('搜索任务').waitFor()
    return page
  }
  const click = (page, name) => page.getByRole('button', { name, exact: true }).click()
  try {
    const teacher = await login('preview_teacher', { width: 1280, height: 800 })
    const student = await login('preview_student1', { width: 390, height: 844 })
    await student.locator('.assignment-card').filter({ hasText: '案例分析：反馈演示' }).click()
    await click(student, '查看收到的反馈 →')
    await student.waitForURL(/#\/assignments\/[^/]+\/feedback$/)
    const original = await student.locator('.source-text').innerText()
    await student.getByRole('button', { name: '记录采纳决定' }).first().click()
    await student.getByLabel('采纳理由').fill('我将补充试点结果。')
    await click(student, '保存采纳记录')
    await student.getByText('我将补充试点结果。', {exact:true}).waitFor()
    await click(student, '开始修订')
    const revised = original + '\n\n补充合成试点结果与比较条件。'
    await student.getByLabel('修订正文').fill(revised)
    await student.getByLabel('修订说明').fill('增加试点数据来源说明')
    await click(student, '保存新修订版本')
    await student.getByText('1 / 5 版').waitFor()
    await student.reload()
    await student.getByText('1 / 5 版').waitFor()
    assert.equal(await student.locator('.source-text').innerText(), original)
    await student.locator('details.check-record > summary').filter({hasText:'修订版 1'}).click()
    await student.getByText('增加试点数据来源说明', {exact:true}).waitFor()
    assert.equal(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await click(student, '学习档案')
    await student.getByRole('heading', {name:/演示学生1的学习档案/}).waitFor()
    await student.getByText('AI 质量提示不是作业成绩', {exact:false}).waitFor()
    assert.equal(await student.locator('.learning-row').count(), 3)
    assert.equal(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await teacher.locator('.assignment-card').filter({ hasText: '案例分析：反馈演示' }).click()
    await click(teacher, '查看教师看板')
    await teacher.waitForURL(/\/dashboard$/)
    await teacher.getByLabel('仅查看高分歧作业').check()
    await teacher.getByText('没有符合筛选条件的作业。').waitFor()
    await teacher.getByLabel('仅查看高分歧作业').uncheck()
    await teacher.locator('details.record > summary').filter({hasText:'演示学生1'}).click()
    await click(teacher, '查看修订轨迹（1 版）')
    await teacher.locator('.revision-list summary').filter({hasText:'修订版 1'}).click()
    await teacher.getByText('增加试点数据来源说明', {exact:true}).waitFor()
    await teacher.locator('.submission-roster li').filter({hasText:'演示学生1'}).getByRole('button', {name:'查看学习档案'}).click()
    await teacher.getByRole('heading', {name:/演示学生1的学习档案/}).waitFor()
    assert.equal(await teacher.locator('.learning-row').count(), 3)
    console.log('PASS student mobile adoption/revision/refresh, teacher desktop history/filter, scoped profile and responsive width')
  } finally {
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
