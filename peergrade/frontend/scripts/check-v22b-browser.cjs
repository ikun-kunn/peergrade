const assert = require('node:assert/strict')
const { chromium } = require(process.env.PEERGRADE_PLAYWRIGHT || 'playwright')

async function main() {
  const origin = new URL(process.env.PEERGRADE_LOCAL_ORIGIN)
  assert.equal(origin.hostname, '127.0.0.1', 'Run only on a fresh local instance seeded with synthetic accounts.')
  assert.equal(origin.protocol, 'http:')
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PEERGRADE_BROWSER })
  async function login(username, viewport) {
    const context = await browser.newContext({ viewport })
    const page = await context.newPage()
    await page.goto(origin.href)
    await page.getByLabel('用户名').fill(username)
    await page.getByLabel('密码').fill('preview123456')
    await page.getByRole('button', { name: '登录 →' }).click()
    await page.getByLabel('搜索任务').waitFor()
    return page
  }
  const navigate = (page, label) => page.getByRole('button', { name: label, exact: true }).click()
  const deadline = hours => {
    const time = new Date(Date.now() + hours * 3600000)
    return new Date(time.getTime() - time.getTimezoneOffset() * 60000).toISOString().slice(0, 16)
  }
  try {
    const teacher = await login('preview_teacher', { width: 1280, height: 800 })
    const student = await login('preview_student1', { width: 390, height: 844 })
    await navigate(teacher, '我的班级')
    await teacher.getByLabel('班级名称').fill('合成浏览器验收班级')
    await navigate(teacher, '创建班级')
    await teacher.getByRole('heading', { name: /合成浏览器验收班级/ }).waitFor()
    const classUrl = teacher.url()
    const code = await teacher.locator('.invite-code').innerText()
    await navigate(student, '我的班级')
    await student.getByLabel('班级邀请码').fill(code)
    await navigate(student, '申请加入')
    await student.getByText('加入申请已提交，等待教师批准。').waitFor()
    assert.equal(await student.getByRole('heading', { name: '批量导入成员' }).count(), 0)
    await navigate(teacher, '刷新班级')
    await teacher.locator('.class-member').filter({ hasText: '演示学生1' }).getByRole('button', { name: '批准' }).click()
    await teacher.getByLabel('学生用户名').fill('preview_student2\npreview_student3')
    await navigate(teacher, '批量导入')
    await teacher.getByText('已批准 3 人 · 待批准 0 人').waitFor()
    await navigate(teacher, '从本班创建任务')
    await teacher.getByLabel('任务名称').fill('验收班级作业')
    await teacher.getByLabel('作业描述').fill('合成班级任务说明')
    await teacher.getByLabel('提交截止').fill(deadline(1))
    await teacher.getByLabel('互评截止').fill(deadline(2))
    await teacher.getByText('已选 3 / 3 人（至少 3 人）').waitFor()
    await teacher.getByRole('button', { name: '创建任务 →' }).click()
    await teacher.locator('.assignment-card').filter({ hasText: '验收班级作业' }).waitFor()
    await navigate(student, '刷新班级')
    await student.getByText('你已加入这个班级。').waitFor()
    await student.locator('.assignment-card').filter({ hasText: '验收班级作业' }).waitFor()
    await navigate(student, '我的任务')
    await student.locator('.assignment-card').filter({ hasText: '案例分析：反馈演示' }).click()
    await student.getByRole('button', { name: '查看收到的反馈' }).click()
    await student.waitForURL(/#\/assignments\/[^/]+\/feedback$/)
    const feedbackUrl = student.url()
    await student.getByRole('button', { name: '申请复核' }).first().click()
    await student.getByLabel('申请理由').fill('请教师核实这条匿名评价的原文依据。')
    await navigate(student, '提交复核申请')
    await student.getByText('我的申请：请教师核实这条匿名评价的原文依据。').waitFor()
    await navigate(teacher, '我的任务')
    await teacher.locator('.assignment-card').filter({ hasText: '案例分析：反馈演示' }).click()
    await navigate(teacher, '查看教师看板')
    await teacher.getByText('待处理 1 条 · 已处理 0 条').waitFor()
    await teacher.getByLabel('仅查看有待处理复核的作业').check()
    await teacher.locator('details.record > summary').click()
    await navigate(teacher, '填写处理意见')
    await teacher.getByLabel('公开处理意见（不含匿名评审身份）').fill('已核对证据，原反馈和分数保留。')
    await teacher.getByLabel('我已核对公开意见不包含评审者身份').check()
    await navigate(teacher, '确认处理')
    await teacher.getByText('待处理 0 条 · 已处理 1 条').waitFor()
    await student.goto(feedbackUrl)
    await student.reload()
    await student.getByText('教师处理意见：已核对证据，原反馈和分数保留。').waitFor()
    assert.equal(await student.getByRole('heading', { name: /匿名评审 [12] · 11 分/ }).count(), 2)
    assert.equal(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await teacher.goto(classUrl)
    await teacher.getByRole('heading', { name: /合成浏览器验收班级/ }).waitFor()
    await teacher.locator('.assignment-card').filter({ hasText: '验收班级作业' }).waitFor()
    console.log('PASS classroom creation/join/approval/import, class assignment, appeal/resolve, refresh and mobile layout')
  } finally {
    await browser.close()
  }
}

main().catch(error => { console.error(error); process.exitCode = 1 })
