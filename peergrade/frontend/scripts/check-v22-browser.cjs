const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { chromium } = require(process.env.PEERGRADE_PLAYWRIGHT || 'playwright')

async function main() {
  const origin = new URL(process.env.PEERGRADE_LOCAL_ORIGIN)
  assert.equal(origin.hostname, '127.0.0.1', 'Use an isolated local instance seeded with synthetic accounts')
  assert.equal(origin.protocol, 'http:')
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PEERGRADE_BROWSER })
  try {
    async function login(context, username) {
      const page = await context.newPage()
      await page.goto(origin.href)
      await page.getByLabel('用户名').fill(username)
      await page.getByLabel('密码').fill('preview123456')
      await page.getByRole('button', { name: '登录 →' }).click()
      await page.getByLabel('搜索任务').waitFor()
      return page
    }
    const teacherContext = await browser.newContext({ viewport: { width: 1280, height: 800 }, acceptDownloads: true })
    const teacher = await login(teacherContext, 'preview_teacher')
    await teacher.getByLabel('搜索任务').fill('反馈演示')
    assert.equal(await teacher.locator('.assignment-card').count(), 1)
    await teacher.locator('.assignment-card').click()
    await teacher.waitForURL(/#\/assignments\/[^/]+$/)
    const assignmentUrl = teacher.url()
    await teacher.reload()
    await teacher.getByRole('button', { name: '查看教师看板' }).waitFor()
    assert.equal(teacher.url(), assignmentUrl)
    await teacher.getByRole('button', { name: '复制为新任务' }).click()
    assert.match(await teacher.getByLabel('任务名称').inputValue(), /反馈演示（副本）$/)
    assert.equal(await teacher.getByLabel('提交截止').inputValue(), '')
    assert.equal(await teacher.getByLabel('互评截止').inputValue(), '')
    await teacher.getByText('已选 0 / 5 人（至少 3 人）').waitFor()
    await teacher.getByRole('button', { name: '返回任务列表' }).click()
    await teacher.locator('.assignment-card').filter({ hasText: '案例分析：反馈演示' }).click()
    await teacher.getByRole('button', { name: '查看教师看板' }).click()
    await teacher.waitForURL(/#\/assignments\/[^/]+\/dashboard$/)
    const dashboardUrl = teacher.url()
    await teacher.reload()
    await teacher.getByRole('link', { name: '导出统计 CSV' }).waitFor()
    assert.equal(teacher.url(), dashboardUrl)
    const downloadEvent = teacher.waitForEvent('download')
    await teacher.getByRole('link', { name: '导出统计 CSV' }).click()
    const download = await downloadEvent
    const csv = await fs.readFile(await download.path(), 'utf8')
    assert.match(csv, /用户名,显示名称,作业提交,收到互评数/)
    assert.match(csv, /preview_student1,演示学生1,已交,2,11\.0,否/)
    const studentContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
    const student = await login(studentContext, 'preview_student1')
    const other = await studentContext.newPage()
    await other.goto(origin.href)
    await other.getByLabel('搜索任务').waitFor()
    for (const page of [student, other]) await page.locator('.task-row').filter({ hasText: '案例分析：互评演示' }).first().click()
    const strengths = page => page.getByPlaceholder('指出值得保留的具体内容')
    await strengths(student).fill('第一端自动保存合成评价')
    await student.locator('.draft-status').getByText('草稿已保存，可稍后继续').waitFor()
    await strengths(other).fill('第二端尚未保存的合成评价')
    await other.locator('.draft-status').getByText(/其他页面已更新草稿/).waitFor()
    assert.equal(await strengths(other).inputValue(), '第二端尚未保存的合成评价')
    other.once('dialog', dialog => dialog.accept())
    await other.getByRole('button', { name: '加载服务器草稿' }).click()
    await other.waitForFunction(() => document.querySelector('textarea').value === '第一端自动保存合成评价')
    await student.waitForURL(/#\/review-tasks\/[^/]+$/)
    const reviewUrl = student.url()
    await student.reload()
    await strengths(student).waitFor()
    assert.equal(student.url(), reviewUrl)
    assert.equal(await strengths(student).inputValue(), '第一端自动保存合成评价')
    // Navigation should persist edits even when the debounce has not elapsed.
    await strengths(student).fill('返回前即时保存的合成评价')
    await student.getByRole('button', { name: '返回任务列表' }).click()
    await student.getByLabel('搜索任务').waitFor()
    await student.goBack()
    await strengths(student).waitFor()
    assert.equal(student.url(), reviewUrl)
    assert.equal(await strengths(student).inputValue(), '返回前即时保存的合成评价')
    assert.equal(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    console.log('PASS desktop search/copy/CSV and deep links; mobile autosave/conflict/reload/navigation and viewport')
  } finally {
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
