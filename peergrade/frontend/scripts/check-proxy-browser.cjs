const assert = require('node:assert/strict')
const { chromium } = require(process.env.PEERGRADE_PLAYWRIGHT || 'playwright')

async function main() {
  const origin = new URL(process.env.PEERGRADE_LOCAL_ORIGIN)
  assert.equal(origin.hostname, '127.0.0.1')
  assert.equal(origin.protocol, 'https:')
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PEERGRADE_BROWSER })
  const password = 'local proxy synthetic password'
  async function login(username, viewport) {
    const context = await browser.newContext({ viewport, ignoreHTTPSErrors: true })
    const page = await context.newPage()
    await page.goto(origin.href)
    await page.getByLabel('用户名').fill(username)
    await page.getByLabel('密码').fill(password)
    await page.getByRole('button', { name: '登录 →' }).click()
    await page.locator('.assignment-card').filter({ hasText: '生产模拟：课程互评' }).click()
    return page
  }
  try {
    const student = await login('proxy_student_0', { width: 390, height: 844 })
    await student.getByRole('button', { name: '查看收到的反馈' }).click()
    await student.getByRole('heading', { name: '匿名评审 1 · 12 分' }).waitFor()
    await student.getByRole('heading', { name: '匿名评审 2 · 12 分' }).waitFor()
    await student.getByRole('button', { name: /跳到匿名评审 1 的第 1 处原文证据/ }).click()
    assert.equal(await student.locator('mark.focused-evidence').textContent(), '原文证据：有效学习需要及时反馈。')
    await student.getByRole('button',{name:'记录采纳决定'}).first().click()
    await student.getByLabel('采纳理由').fill('依据反馈补充学习数据。')
    await student.getByRole('button',{name:'保存采纳记录'}).click()
    await student.getByText('依据反馈补充学习数据。',{exact:true}).waitFor()
    await student.getByRole('button',{name:'开始修订'}).click()
    const source = await student.locator('.source-text').innerText()
    await student.getByLabel('修订正文').fill(source+'\n补充合成前后测试结果。')
    await student.getByLabel('修订说明').fill('合成修订说明')
    await student.getByRole('button',{name:'保存新修订版本'}).click()
    await student.getByText('1 / 5 版').waitFor()
    await student.reload()
    await student.getByText('1 / 5 版').waitFor()
    assert.equal(await student.locator('.source-text').innerText(),source)
    assert.equal(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    const teacher = await login('proxy_teacher', { width: 1280, height: 800 })
    await teacher.getByRole('button', { name: '查看教师看板' }).click()
    await teacher.getByText('6 / 6 条', { exact: true }).waitFor()
    await teacher.getByText('3 / 3 人', { exact: true }).waitFor()
    assert.equal(await teacher.locator('.submission-roster li').count(), 3)
    await teacher.locator('details.record > summary').filter({hasText:'合成学生 1'}).click()
    await teacher.getByRole('button',{name:'查看修订轨迹（1 版）'}).click()
    await teacher.locator('.revision-list summary').filter({hasText:'修订版 1'}).click()
    await teacher.getByText('合成修订说明',{exact:true}).waitFor()
    await teacher.locator('.submission-roster li').filter({hasText:'合成学生 1'}).getByRole('button',{name:'查看学习档案'}).click()
    await teacher.getByRole('heading',{name:/合成学生 1的学习档案/}).waitFor()
    await student.getByRole('button',{name:'账号安全',exact:true}).click()
    await student.getByLabel('当前密码',{exact:true}).fill(password)
    await student.getByLabel('新密码',{exact:true}).fill('new local proxy browser password')
    await student.getByLabel('确认新密码',{exact:true}).fill('new local proxy browser password')
    await student.getByRole('button',{name:'修改密码并重新登录',exact:true}).click()
    await student.getByText('密码已修改，所有登录会话已失效，请使用新密码重新登录').waitFor()
    await student.getByLabel('用户名').fill('proxy_student_0')
    await student.getByLabel('密码',{exact:true}).fill('new local proxy browser password')
    await student.getByRole('button',{name:'登录 →',exact:true}).click()
    await student.getByLabel('搜索任务').waitFor()
    console.log('PASS: local Caddy TLS browser feedback, revision, teacher profile, and secure account password change')
  } finally {
    await browser.close()
  }
}

main().catch(error => { console.error(error); process.exitCode = 1 })
